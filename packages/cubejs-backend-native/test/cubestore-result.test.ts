const message = (bytes: number[]) => Buffer.from(bytes);

const rows = (result: native.ResultWrapper) => native.getCubestoreResult(result.getRawData()[0]);

const EXPECTED = [
  { id: '1', name: 'foo' },
  { id: '2', name: null },
  { id: '3', name: 'baz' },
];

describe('parseCubestoreResultMessage', () => {
  describe.each([
    ['legacy', LEGACY_RESULT_SET_MESSAGE],
    ['arrow', ARROW_RESULT_SET_MESSAGE],
  ])('%s result set', (_format, bytes) => {
    it('parses', async () => {
      const result = await native.parseCubestoreResultMessage(message(bytes));

      expect(rows(result)).toEqual(EXPECTED);
    });

    it('iterates over rows', async () => {
      const result = await native.parseCubestoreResultMessage(message(bytes));

      // ResultWrapper's proxy implements Symbol.iterator, but its type doesn't declare it.
      const iterated = [];

      for (const row of result as unknown as Iterable<native.ResultRow>) {
        iterated.push(row);
      }

      expect(iterated).toEqual(EXPECTED);
    });

    it('serializes to JSON', async () => {
      const result = await native.parseCubestoreResultMessage(message(bytes));

      expect(JSON.parse(JSON.stringify(result))).toEqual(EXPECTED);
    });

    it('parses a buffer that is a view into a larger allocation', async () => {
      const msg = message(bytes);
      const backing = Buffer.alloc(msg.length + 16, 0xff);
      msg.copy(backing, 7);

      const result = await native.parseCubestoreResultMessage(backing.subarray(7, 7 + msg.length));

      expect(rows(result)).toEqual(EXPECTED);
    });

    it('rejects a truncated message', async () => {
      const msg = message(bytes);

      await expect(native.parseCubestoreResultMessage(msg.subarray(0, msg.length / 2)))
        .rejects.toThrow(/FlatBuffer/);
    });

    it('parses the same buffer concurrently', async () => {
      const msg = message(bytes);

      const results = await Promise.all(
        Array.from({ length: 64 }, () => native.parseCubestoreResultMessage(msg))
      );

      for (const result of results) {
        expect(rows(result)).toEqual(EXPECTED);
      }
    });
  });

  it('rejects with the Cube Store error message', async () => {
    await expect(native.parseCubestoreResultMessage(message(ERROR_MESSAGE)))
      .rejects.toThrow('Table not found');
  });

  it('rejects an empty buffer', async () => {
    await expect(native.parseCubestoreResultMessage(Buffer.alloc(0)))
      .rejects.toThrow(/FlatBuffer/);
  });

  it('rejects a malformed message', async () => {
    await expect(native.parseCubestoreResultMessage(Buffer.from('definitely not a flatbuffer')))
      .rejects.toThrow(/FlatBuffer/);
  });
});
